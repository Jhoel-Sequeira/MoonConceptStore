BEGIN;

CREATE TABLE IF NOT EXISTS public.renta_config (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  marca_id integer NOT NULL UNIQUE REFERENCES public.marcas(id),
  monto_mensual numeric(12,2) NOT NULL CHECK (monto_mensual > 0),
  dia_vencimiento smallint NOT NULL DEFAULT 1 CHECK (dia_vencimiento BETWEEN 1 AND 31),
  fecha_inicio date NOT NULL,
  fecha_fin date,
  activa boolean NOT NULL DEFAULT true,
  creado_en timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT renta_config_fechas_check CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_inicio)
);

ALTER TABLE public.renta
  ADD COLUMN IF NOT EXISTS periodo date,
  ADD COLUMN IF NOT EXISTS fecha_vencimiento date,
  ADD COLUMN IF NOT EXISTS config_id integer;
ALTER TABLE public.renta ALTER COLUMN monto TYPE numeric(12,2) USING round(monto::numeric, 2);
ALTER TABLE public.renta_pago
  ADD COLUMN IF NOT EXISTS referencia_pago text;
ALTER TABLE public.renta_pago ALTER COLUMN monto_pagado TYPE numeric(12,2) USING round(monto_pagado::numeric, 2);

UPDATE public.renta
SET fecha_vencimiento = COALESCE(fecha_vencimiento, fecha_pago::date),
    periodo = COALESCE(periodo, date_trunc('month', fecha_pago)::date)
WHERE fecha_pago IS NOT NULL;

UPDATE public.renta_pago
SET referencia_pago = COALESCE(NULLIF(trim(referencia_pago), ''), NULLIF(trim(comentario), ''), 'Registro anterior')
WHERE referencia_pago IS NULL OR trim(referencia_pago) = '';
ALTER TABLE public.renta_pago ALTER COLUMN referencia_pago SET NOT NULL;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_renta_config') THEN
    ALTER TABLE public.renta ADD CONSTRAINT fk_renta_config
      FOREIGN KEY (config_id) REFERENCES public.renta_config(id) ON DELETE SET NULL;
  END IF;
END $$;

CREATE UNIQUE INDEX IF NOT EXISTS renta_marca_periodo_uidx
  ON public.renta (marca_id, periodo);
CREATE INDEX IF NOT EXISTS ix_renta_pago_renta_id
  ON public.renta_pago (renta_id);
ALTER TABLE public.renta_config ENABLE ROW LEVEL SECURITY;

COMMIT;
