BEGIN;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM public.estados
    WHERE modulo = 'ventas' AND nombre = 'Anulada'
  ) THEN
    INSERT INTO public.estados (modulo, nombre, descripcion)
    VALUES ('ventas', 'Anulada', 'Venta cancelada mediante devolución total');
  END IF;
END;
$$;

CREATE TABLE public.devoluciones_venta (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venta_id integer NOT NULL UNIQUE REFERENCES public.ventas(id) ON DELETE RESTRICT,
  fecha_devolucion timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
  motivo text NOT NULL CHECK (length(trim(motivo)) > 0),
  monto_reembolso numeric(12, 2) NOT NULL CHECK (monto_reembolso >= 0),
  metodo_reembolso varchar(100) NOT NULL,
  estado_reembolso varchar(20) NOT NULL DEFAULT 'Pendiente'
    CHECK (estado_reembolso IN ('Pendiente', 'Reembolsado')),
  reembolsado_en timestamp without time zone,
  CHECK ((estado_reembolso = 'Pendiente' AND reembolsado_en IS NULL)
      OR (estado_reembolso = 'Reembolsado' AND reembolsado_en IS NOT NULL))
);

CREATE TABLE public.devoluciones_venta_detalles (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  devolucion_id bigint NOT NULL REFERENCES public.devoluciones_venta(id) ON DELETE RESTRICT,
  venta_detalle_id integer NOT NULL UNIQUE REFERENCES public.venta_detalles(id) ON DELETE RESTRICT,
  producto_id integer NOT NULL REFERENCES public.productos(id) ON DELETE RESTRICT,
  cantidad integer NOT NULL CHECK (cantidad > 0),
  monto_devuelto numeric(12, 2) NOT NULL CHECK (monto_devuelto >= 0)
);

CREATE INDEX devoluciones_venta_fecha_idx ON public.devoluciones_venta(fecha_devolucion DESC);
CREATE INDEX devoluciones_venta_detalles_devolucion_idx ON public.devoluciones_venta_detalles(devolucion_id);

ALTER TABLE public.devoluciones_venta ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.devoluciones_venta_detalles ENABLE ROW LEVEL SECURITY;

CREATE SCHEMA IF NOT EXISTS internal;
REVOKE ALL ON SCHEMA internal FROM PUBLIC, anon, authenticated;
GRANT USAGE ON SCHEMA internal TO service_role;

CREATE OR REPLACE FUNCTION internal.registrar_devolucion_venta(p_venta_id integer, p_motivo text)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public, internal
AS $$
DECLARE
  v_total numeric(12, 2);
  v_usuario_id integer;
  v_estado text;
  v_metodo_pago varchar(100);
  v_pago_total numeric(12, 2);
  v_estado_anulada_id integer;
  v_devolucion_id bigint;
  v_line record;
BEGIN
  IF p_venta_id IS NULL OR p_venta_id <= 0 THEN
    RAISE EXCEPTION 'Número de factura inválido';
  END IF;
  IF p_motivo IS NULL OR length(trim(p_motivo)) < 5 THEN
    RAISE EXCEPTION 'El motivo debe tener al menos 5 caracteres';
  END IF;

  SELECT v.total, v.usuario_id, e.nombre, mp.metodo_pago
    INTO v_total, v_usuario_id, v_estado, v_metodo_pago
  FROM public.ventas v
  JOIN public.estados e ON e.id = v.estado_id AND e.modulo = 'ventas'
  JOIN public.metodo_pago mp ON mp.id = v.metodo_pago_id
  WHERE v.id = p_venta_id
  FOR UPDATE OF v;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'No existe la factura %', p_venta_id;
  END IF;
  IF v_estado <> 'Facturada' THEN
    RAISE EXCEPTION 'La factura % no está Facturada (estado actual: %)', p_venta_id, v_estado;
  END IF;

  SELECT COALESCE(sum(p.monto), 0)::numeric(12, 2)
    INTO v_pago_total
  FROM public.pagos_venta p
  WHERE p.venta_id = p_venta_id;
  IF v_pago_total <> v_total THEN
    RAISE EXCEPTION 'Los pagos registrados (%) no coinciden con el total de la factura (%)', v_pago_total, v_total;
  END IF;

  PERFORM p.id
  FROM public.productos p
  JOIN public.venta_detalles vd ON vd.producto_id = p.id
  WHERE vd.venta_id = p_venta_id
  ORDER BY p.id
  FOR UPDATE OF p;

  SELECT id INTO v_estado_anulada_id
  FROM public.estados
  WHERE modulo = 'ventas' AND nombre = 'Anulada'
  ORDER BY id
  LIMIT 1;
  IF v_estado_anulada_id IS NULL THEN
    RAISE EXCEPTION 'No está configurado el estado Anulada para ventas';
  END IF;

  INSERT INTO public.devoluciones_venta
    (venta_id, motivo, monto_reembolso, metodo_reembolso)
  VALUES
    (p_venta_id, trim(p_motivo), v_total, v_metodo_pago)
  RETURNING id INTO v_devolucion_id;

  FOR v_line IN
    SELECT vd.id, vd.producto_id, vd.cantidad, vd.subtotal
    FROM public.venta_detalles vd
    WHERE vd.venta_id = p_venta_id
    ORDER BY vd.producto_id, vd.id
  LOOP
    INSERT INTO public.devoluciones_venta_detalles
      (devolucion_id, venta_detalle_id, producto_id, cantidad, monto_devuelto)
    VALUES
      (v_devolucion_id, v_line.id, v_line.producto_id, v_line.cantidad, v_line.subtotal);

    INSERT INTO public.kardex
      (producto_id, usuario_id, tipo_movimiento, cantidad, referencia_id, motivo)
    VALUES
      (v_line.producto_id, v_usuario_id, 'AJUSTE_POSITIVO', v_line.cantidad,
       p_venta_id, format('Devolución de factura #%s: %s', p_venta_id, trim(p_motivo)));
  END LOOP;

  UPDATE public.ventas
  SET estado_id = v_estado_anulada_id
  WHERE id = p_venta_id;

  RETURN jsonb_build_object(
    'devolucion_id', v_devolucion_id,
    'venta_id', p_venta_id,
    'monto_reembolso', v_total,
    'metodo_reembolso', v_metodo_pago,
    'estado_reembolso', 'Pendiente'
  );
END;
$$;

REVOKE ALL ON FUNCTION internal.registrar_devolucion_venta(integer, text) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION internal.registrar_devolucion_venta(integer, text) TO service_role;

COMMIT;
