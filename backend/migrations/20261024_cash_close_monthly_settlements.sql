BEGIN;

CREATE TABLE IF NOT EXISTS public.cierres_caja (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fecha date NOT NULL UNIQUE,
  usuario_id integer NOT NULL REFERENCES public.usuarios(id),
  fondo_inicial numeric(12,2) NOT NULL CHECK (fondo_inicial >= 0),
  esperado_efectivo numeric(12,2) NOT NULL,
  esperado_tarjeta numeric(12,2) NOT NULL,
  esperado_transferencia numeric(12,2) NOT NULL,
  contado_efectivo numeric(12,2) NOT NULL CHECK (contado_efectivo >= 0),
  contado_tarjeta numeric(12,2) NOT NULL CHECK (contado_tarjeta >= 0),
  contado_transferencia numeric(12,2) NOT NULL CHECK (contado_transferencia >= 0),
  observaciones text,
  cerrado_en timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE public.liquidaciones
  ADD COLUMN IF NOT EXISTS total_comision_tienda numeric(12,2) NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS fecha_pago date,
  ADD COLUMN IF NOT EXISTS referencia_pago text;

ALTER TABLE public.liquidacion_detalles
  ADD COLUMN IF NOT EXISTS monto_transferencia numeric(12,2) NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS comision_tienda numeric(12,2) NOT NULL DEFAULT 0;

CREATE UNIQUE INDEX IF NOT EXISTS liquidaciones_marca_periodo_uidx
  ON public.liquidaciones (marca_id, periodo_inicio, periodo_fin);
ALTER TABLE public.cierres_caja ENABLE ROW LEVEL SECURITY;

INSERT INTO public.estados (modulo, nombre, descripcion)
SELECT 'liquidaciones', 'Pendiente', 'Liquidación mensual pendiente de pago'
WHERE NOT EXISTS (SELECT 1 FROM public.estados WHERE modulo = 'liquidaciones' AND nombre = 'Pendiente');
INSERT INTO public.estados (modulo, nombre, descripcion)
SELECT 'liquidaciones', 'Pagado', 'Liquidación pagada con fecha y referencia registradas'
WHERE NOT EXISTS (SELECT 1 FROM public.estados WHERE modulo = 'liquidaciones' AND nombre = 'Pagado');

COMMIT;
