CREATE TABLE IF NOT EXISTS public.articulos (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo varchar(100) NOT NULL UNIQUE,
  marca_id integer NOT NULL REFERENCES public.marcas(id),
  categoria varchar(100) NOT NULL,
  detalles_rubro jsonb NOT NULL DEFAULT '{}'::jsonb,
  nombre varchar(255) NOT NULL,
  descripcion text,
  precio numeric(12,2) NOT NULL,
  stock_critico integer NOT NULL DEFAULT 5 CHECK (stock_critico >= 0),
  imagen_url text,
  imagenes jsonb NOT NULL DEFAULT '[]'::jsonb,
  estado_id integer NOT NULL DEFAULT 1
);

ALTER TABLE public.productos
  ADD COLUMN IF NOT EXISTS articulo_id integer REFERENCES public.articulos(id) ON DELETE CASCADE,
  ADD COLUMN IF NOT EXISTS color varchar(100);

CREATE INDEX IF NOT EXISTS ix_productos_articulo_id ON public.productos(articulo_id);
