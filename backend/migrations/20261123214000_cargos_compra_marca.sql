BEGIN;

ALTER TABLE public.ventas
  ADD COLUMN IF NOT EXISTS marca_cliente_id integer REFERENCES public.marcas(id),
  ADD COLUMN IF NOT EXISTS descontar_de_liquidacion boolean NOT NULL DEFAULT false;

ALTER TABLE public.ventas
  ADD CONSTRAINT ventas_deduccion_marca_check
  CHECK (NOT descontar_de_liquidacion OR marca_cliente_id IS NOT NULL);

ALTER TABLE public.liquidaciones
  ADD COLUMN IF NOT EXISTS total_deducciones_marca numeric(12,2) NOT NULL DEFAULT 0;

CREATE TABLE public.cargos_marca (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venta_id integer NOT NULL UNIQUE REFERENCES public.ventas(id),
  marca_id integer NOT NULL REFERENCES public.marcas(id),
  monto numeric(12,2) NOT NULL CHECK (monto > 0),
  creado_en timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE public.liquidacion_cargos_marca (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cargo_id bigint NOT NULL REFERENCES public.cargos_marca(id),
  liquidacion_id integer NOT NULL REFERENCES public.liquidaciones(id),
  monto_aplicado numeric(12,2) NOT NULL CHECK (monto_aplicado > 0),
  creado_en timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (cargo_id, liquidacion_id)
);

CREATE INDEX ix_cargos_marca_marca_fecha ON public.cargos_marca(marca_id, creado_en, id);
CREATE INDEX ix_liquidacion_cargos_marca_liquidacion ON public.liquidacion_cargos_marca(liquidacion_id);
ALTER TABLE public.cargos_marca ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.liquidacion_cargos_marca ENABLE ROW LEVEL SECURITY;

INSERT INTO public.metodo_pago (metodo_pago)
SELECT 'Cuenta de marca'
WHERE NOT EXISTS (SELECT 1 FROM public.metodo_pago WHERE lower(trim(metodo_pago)) = 'cuenta de marca');

COMMIT;
