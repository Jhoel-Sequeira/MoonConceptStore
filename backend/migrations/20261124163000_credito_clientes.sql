BEGIN;

INSERT INTO public.metodo_pago (metodo_pago)
SELECT 'Crédito'
WHERE NOT EXISTS (
  SELECT 1 FROM public.metodo_pago WHERE lower(trim(metodo_pago)) = lower('Crédito')
);

ALTER TABLE public.liquidacion_detalles
  ADD COLUMN IF NOT EXISTS monto_credito numeric(12,2) NOT NULL DEFAULT 0;

CREATE TABLE public.cuentas_cobrar_clientes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  venta_id integer NOT NULL UNIQUE REFERENCES public.ventas(id) ON DELETE RESTRICT,
  cliente_id bigint NOT NULL REFERENCES public.clientes(id) ON DELETE RESTRICT,
  monto_original numeric(12,2) NOT NULL CHECK (monto_original > 0),
  creado_en timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE public.abonos_cuenta_cliente (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cuenta_id bigint NOT NULL REFERENCES public.cuentas_cobrar_clientes(id) ON DELETE RESTRICT,
  monto numeric(12,2) NOT NULL CHECK (monto > 0),
  metodo_pago varchar(100) NOT NULL CHECK (metodo_pago IN ('Efectivo', 'Tarjeta', 'Transferencia')),
  referencia varchar(120),
  registrado_por integer NOT NULL REFERENCES public.usuarios(id) ON DELETE RESTRICT,
  fecha_pago timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX ix_cuentas_cobrar_cliente ON public.cuentas_cobrar_clientes(cliente_id, creado_en, id);
CREATE INDEX ix_abonos_cuenta_fecha ON public.abonos_cuenta_cliente(cuenta_id, fecha_pago, id);

ALTER TABLE public.cuentas_cobrar_clientes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.abonos_cuenta_cliente ENABLE ROW LEVEL SECURITY;

COMMIT;
