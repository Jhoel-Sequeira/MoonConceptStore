ALTER TABLE public.usuarios
  ADD COLUMN IF NOT EXISTS auth_version integer NOT NULL DEFAULT 0;

CREATE TABLE IF NOT EXISTS public.password_reset_tokens (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
  token_hash character varying(64) NOT NULL UNIQUE,
  created_at timestamp with time zone NOT NULL,
  expires_at timestamp with time zone NOT NULL,
  used_at timestamp with time zone
);

CREATE INDEX IF NOT EXISTS ix_password_reset_tokens_user_created
  ON public.password_reset_tokens(user_id, created_at);

ALTER TABLE public.password_reset_tokens ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.password_reset_tokens FROM anon, authenticated;
