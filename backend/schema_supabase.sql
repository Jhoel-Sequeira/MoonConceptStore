  utilidad_nio numeric(12,2) GENERATED ALWAYS AS (round((((COALESCE(costo_nio, (0)::numeric) + costo_envio_nio) * margen_utilidad_pct) / (100)::numeric), 2)) STORED,
  precio_sugerido_nio numeric(12,2) GENERATED ALWAYS AS (round(((COALESCE(costo_nio, (0)::numeric) + costo_envio_nio) * ((1)::numeric + (margen_utilidad_pct / (100)::numeric))), 2)) STORED,
  precio_minimo_nio numeric(12,2) GENERATED ALWAYS AS (round((COALESCE(costo_nio, (0)::numeric) + costo_envio_nio), 2)) STORED,
  CONSTRAINT productos_pkey PRIMARY KEY (id),
  CONSTRAINT productos_stock_critico_check CHECK (stock_critico >= 0)
);

